import Foundation
@main struct Checks {
 static func main() {
  precondition(!CapturePolicy.allows(page: 7, usage: 4), "Typed text must never be captured")
  precondition(CapturePolicy.allows(page: 7, usage: 58))
  precondition(CapturePolicy.allows(page: 7, usage: 115))
  precondition(!CapturePolicy.allows(page: 7, usage: 40))
  precondition(CapturePolicy.allows(page: 12, usage: 233))
  precondition(CapturePolicy.allows(page: 9, usage: 4))
  precondition(!CapturePolicy.allows(page: 9, usage: 1))
  precondition(!CapturePolicy.allows(page: 9, usage: 2))
  precondition(!CapturePolicy.allows(page: 12, usage: UInt32.max))
  precondition(!CapturePolicy.allows(page: 12, usage: 65535))
  precondition(CapturePolicy.label(page: 12, usage: 233) == "Subir volumen")
  precondition(!CapturePolicy.allows(page: 1, usage: 48), "Motion must not trigger actions")
  let rule = Mapping(source: "receiver:12:233", action: "volumeUp", keyCode: 0, modifiers: 0)
  precondition(try! JSONDecoder().decode(Mapping.self, from: JSONEncoder().encode(rule)) == rule)
  precondition(rule.controlLabel == "Subir volumen")
  let back = Mapping(source:"receiver|endpoint=1133:50475:123456:65280:1|slot=1|route=synthetic1B04|button=4",action:"shortcut",keyCode:33,modifiers:1048576)
  precondition(back.controlLabel == "Atrás (botón 4)" && back.actionLabel == "⌘[")
  let calculator = Mapping(source:"1133:50475:123456:1:2:12:402",action:"launchCalculator",keyCode:0,modifiers:0)
  precondition(calculator.controlLabel == "Calculadora" && calculator.actionLabel == "Abrir Calculadora")
  let legacy = Data("{\"source\":\"receiver:12:233\",\"action\":\"volumeUp\",\"keyCode\":0,\"modifiers\":0}".utf8)
  precondition(try! JSONDecoder().decode(Mapping.self,from:legacy).isEnabled, "Existing mappings must remain enabled")
  var paused = back; paused.isEnabled = false
  precondition(!(try! JSONDecoder().decode(Mapping.self,from:JSONEncoder().encode(paused))).isEnabled)
  let app = ApplicationTarget(name:"TextEdit",path:"/System/Applications/TextEdit.app",bundleIdentifier:"com.apple.TextEdit",bookmark:nil)
  let launch = Mapping(source:"test",action:"launchApplication",keyCode:0,modifiers:0,application:app)
  precondition(try! JSONDecoder().decode(Mapping.self,from:JSONEncoder().encode(launch)) == launch)
  precondition(launch.actionLabel == "Abrir TextEdit")
  precondition((try! JSONDecoder().decode(Mapping.self,from:legacy)).application == nil)
  let audio = Mapping(source:"keyboard-test",action:"digitalVolumeDown",keyCode:0,modifiers:0,audioOutputUID:"output-test")
  precondition(audio.isDigitalVolumeAction)
  precondition(try! JSONDecoder().decode(Mapping.self,from:JSONEncoder().encode(audio)) == audio)
  precondition((try! JSONDecoder().decode(Mapping.self,from:legacy)).audioOutputUID == nil)
  precondition(!rule.isDigitalVolumeAction)
  print("Capture privacy and mapping persistence checks passed")
 }
}
